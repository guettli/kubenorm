package normalize

import (
	"fmt"
	"regexp"
	"slices"
	"strings"

	"k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"
)

const (
	kindNamespace      = "Namespace"
	kindClusterRole    = "ClusterRole"
	kindServiceAccount = "ServiceAccount"
	kindConfigMap      = "ConfigMap"

	rbacGroup         = "rbac.authorization.k8s.io"
	bootstrappingKey  = "kubernetes.io/bootstrapping"
	rbacDefaultsValue = "rbac-defaults"
	kubeRootCAName    = "kube-root-ca.crt"
	defaultName       = "default"
)

// Include reports whether the item passes all filters of o (skip rules,
// excluded namespaces, kind/name/namespace filters and SkipOwned).
// isNamespaced tells whether the resource is namespace-scoped. For resources
// read from files, a resource is namespaced if metadata.namespace is set.
func (o *Options) Include(item *unstructured.Unstructured, isNamespaced bool) bool {
	return o.skipReason(item, isNamespaced) == ""
}

// skipReason returns why the item is dropped, or "" if it is kept.
func (o *Options) skipReason(item *unstructured.Unstructured, isNamespaced bool) string {
	if o.SkipOwned {
		if hasControllingOwner(item) {
			return "--skip-owned: has a controlling ownerReference"
		}

		if isAutogeneratedByKubernetes(item) {
			return "--skip-owned: generated by Kubernetes"
		}
	}

	var (
		skipRules []skipRule
		excludes  []string
	)

	if o.Config != nil {
		skipRules = o.Config.skipRules
		excludes = o.Config.excludeNamespaces
	}

	if pattern := excludedNamespacePattern(item, isNamespaced, excludes); pattern != "" {
		return "excludeNamespaces " + pattern
	}

	if len(skipRules) > 0 {
		identity := identityOf(item, isNamespaced)
		for _, rule := range skipRules {
			if rule.matches(identity) {
				return rule.Origin
			}
		}
	}

	return o.flagFilterReason(item, isNamespaced)
}

// flagFilterReason returns why the --kind, --name-regex or --namespaces
// filter drops the item, or "".
func (o *Options) flagFilterReason(item *unstructured.Unstructured, isNamespaced bool) string {
	if len(o.Kinds) > 0 && !matchesAnyGlob(o.Kinds, item.GetKind()) {
		return "--kind: kind does not match"
	}

	if o.NameRegex != nil && !o.NameRegex.MatchString(item.GetName()) {
		return "--name-regex: name does not match"
	}

	if len(o.Namespaces) == 0 {
		return ""
	}

	namespace := item.GetNamespace()

	switch {
	case isNamespaced:
	case isNamespaceObject(item):
		namespace = item.GetName()
	default:
		return "--namespaces: cluster-scoped resource"
	}

	if !slices.Contains(o.Namespaces, namespace) {
		return "--namespaces: namespace not selected"
	}

	return ""
}

// ParseNamespacesCSV parses a comma-separated list of namespace names.
// An empty string returns nil (match all).
func ParseNamespacesCSV(namespacesCSV string) ([]string, error) {
	if strings.TrimSpace(namespacesCSV) == "" {
		return nil, nil
	}

	var filter []string

	for namespace := range strings.SplitSeq(namespacesCSV, ",") {
		namespace = strings.TrimSpace(namespace)
		if namespace == "" {
			continue
		}

		if !slices.Contains(filter, namespace) {
			filter = append(filter, namespace)
		}
	}

	if len(filter) == 0 {
		return nil, fmt.Errorf("invalid namespace list %q: no namespace names found", namespacesCSV)
	}

	return filter, nil
}

// ParseKindsCSV parses a comma-separated list of kind globs.
// An empty string returns nil (match all).
func ParseKindsCSV(kindFilterCSV string) ([]string, error) {
	trimmed := strings.TrimSpace(kindFilterCSV)
	if trimmed == "" {
		return nil, nil
	}

	patterns := make([]string, 0)

	for entry := range strings.SplitSeq(trimmed, ",") {
		entry = strings.TrimSpace(entry)
		if entry == "" {
			continue
		}

		err := validateGlobPattern(entry)
		if err != nil {
			return nil, fmt.Errorf("invalid kind glob %q: %w", entry, err)
		}

		patterns = append(patterns, entry)
	}

	if len(patterns) == 0 {
		return nil, fmt.Errorf("invalid kind list %q: no patterns found", kindFilterCSV)
	}

	return patterns, nil
}

// ParseNameRegex compiles the regex. An empty string returns nil (match all).
func ParseNameRegex(nameRegex string) (*regexp.Regexp, error) {
	trimmed := strings.TrimSpace(nameRegex)
	if trimmed == "" {
		return nil, nil //nolint:nilnil // nil means: no filter
	}

	re, err := regexp.Compile(trimmed)
	if err != nil {
		return nil, fmt.Errorf("invalid name regex %q: %w", nameRegex, err)
	}

	return re, nil
}

// excludedNamespacePattern returns the first pattern of an excluded namespace
// the item lives in (or is), or "". Namespace objects are matched by their
// name; every other resource is matched by its metadata.namespace.
func excludedNamespacePattern(item *unstructured.Unstructured, isNamespaced bool, patterns []string) string {
	if len(patterns) == 0 {
		return ""
	}

	target := ""

	switch {
	case isNamespaced:
		target = item.GetNamespace()
	case isNamespaceObject(item):
		target = item.GetName()
	}

	if target == "" {
		return ""
	}

	for _, pattern := range patterns {
		if matchGlob(pattern, target) {
			return pattern
		}
	}

	return ""
}

// isNamespaceObject reports whether the item is a core Namespace object.
func isNamespaceObject(item *unstructured.Unstructured) bool {
	return item.GetKind() == kindNamespace && getGroup(item.GetAPIVersion()) == ""
}

func hasControllingOwner(item *unstructured.Unstructured) bool {
	for _, ref := range item.GetOwnerReferences() {
		if ref.Controller != nil && *ref.Controller {
			return true
		}
	}

	return false
}

// isAutogeneratedByKubernetes reports whether the item is one that Kubernetes
// itself creates and maintains, rather than something a user authored. Such
// resources have no controlling owner reference but are still effectively
// "owned" by the control plane.
func isAutogeneratedByKubernetes(item *unstructured.Unstructured) bool {
	return isAggregatedClusterRole(item) ||
		isRBACBootstrapResource(item) ||
		isDefaultServiceAccount(item) ||
		isKubeRootCAConfigMap(item)
}

// isAggregatedClusterRole reports whether the item is a ClusterRole whose
// `rules` are autogenerated by the Kubernetes RBAC controller from other
// ClusterRoles via `aggregationRule.clusterRoleSelectors`.
func isAggregatedClusterRole(item *unstructured.Unstructured) bool {
	gvk := item.GroupVersionKind()
	if gvk.Group != rbacGroup || gvk.Kind != kindClusterRole {
		return false
	}

	rule, found, err := unstructured.NestedMap(item.Object, "aggregationRule")
	if err != nil || !found {
		return false
	}

	return len(rule) > 0
}

// isRBACBootstrapResource reports whether the item is a default RBAC resource
// installed by the Kubernetes bootstrap process. Those resources carry the
// label `kubernetes.io/bootstrapping=rbac-defaults` and are reconciled by the
// apiserver on every start, so user edits get overwritten.
func isRBACBootstrapResource(item *unstructured.Unstructured) bool {
	if item.GroupVersionKind().Group != rbacGroup {
		return false
	}

	return item.GetLabels()[bootstrappingKey] == rbacDefaultsValue
}

// isDefaultServiceAccount reports whether the item is the `default`
// ServiceAccount that the service-account controller creates in every
// namespace.
func isDefaultServiceAccount(item *unstructured.Unstructured) bool {
	gvk := item.GroupVersionKind()
	return gvk.Group == "" && gvk.Kind == kindServiceAccount && item.GetName() == defaultName
}

// isKubeRootCAConfigMap reports whether the item is the `kube-root-ca.crt`
// ConfigMap that the root-ca-cert-publisher controller creates in every
// namespace.
func isKubeRootCAConfigMap(item *unstructured.Unstructured) bool {
	gvk := item.GroupVersionKind()
	return gvk.Group == "" && gvk.Kind == kindConfigMap && item.GetName() == kubeRootCAName
}
